      const isMobile = window.innerWidth <= 991;

      document.querySelectorAll(".main-header .navigation li.dropdown > a").forEach(function (link) {

        const submenu = link.nextElementSibling;

        // If no submenu → ignore
        if (!submenu || submenu.tagName !== "UL") return;

        // DESKTOP → allow normal navigation
        if (!isMobile) {
          link.addEventListener("click", function (e) {
            window.location = this.href; // force navigation
          });
          return;
        }

        // MOBILE → first tap opens submenu, second tap navigates
        link.addEventListener("click", function (e) {

          if (!submenu.classList.contains("open-submenu")) {
            e.preventDefault();
            submenu.classList.add("open-submenu");
            return;
          }

          // If already open → allow navigation
        });

      });
    });
